#!/usr/bin/env python3
"""Compare two sanitized read-only pfSense Unbound reports.

The reports are generated by:
  PFSENSE_OUTPUT=verbose just pfsense-unbound-restart-check

Do not mistake changed PID, matching config hashes, or pfBlockerNG
context headers for a timestamped caller trace. Output is categorical,
without copying source log lines, feed URLs or credentials.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timedelta
from pathlib import Path
import re
import sys


MAX_REPORT_BYTES = 512 * 1024
FINGERPRINTS = ("unbound_config", "dnsbl_legacy_ini", "dnsbl_python_ini")
HEADERS = {
    "pfblocker_unbound_stop_marker": "stop",
    "pfblocker_unbound_start_marker": "start",
}


def load_report(filename: str) -> str:
    path = Path(filename)
    if path.is_symlink() or not path.is_file() or path.stat().st_size > MAX_REPORT_BYTES:
        raise ValueError("report missing, symlinked or exceeds the bounded input limit")
    with path.open("rb") as handle:
        data = handle.read(MAX_REPORT_BYTES + 1)
    if len(data) > MAX_REPORT_BYTES:
        raise ValueError("report exceeds the bounded input limit")
    return data.decode("utf-8", errors="replace")


def field(text: str, pattern: str) -> str | None:
    match = re.search(pattern, text, re.MULTILINE)
    return match.group(1) if match else None


def parse_time(value: str | None) -> datetime | None:
    if not value:
        return None
    try:
        return datetime.strptime(value, "%Y-%m-%dT%H:%M:%S%z")
    except ValueError:
        return None


def report_time(text: str) -> datetime | None:
    return parse_time(field(text, r"^pfSense_time=(\S+)$"))


def pid(text: str) -> str | None:
    return field(text, r"^unbound_pid=([0-9]+)\s+started_local=")


def started_local(text: str) -> datetime | None:
    stamp = field(text, r"^unbound_pid=[0-9]+\s+started_local=([A-Za-z0-9_:]+)")
    if not stamp:
        return None
    try:
        return datetime.strptime(stamp, "%a_%b_%d_%H:%M:%S_%Y")
    except ValueError:
        return None


def fingerprint(text: str, label: str) -> str | None:
    match = re.search(
        r"(?m)^config_fingerprint=" + re.escape(label)
        + r"\s+[^\n]*?\bsha256=([a-f0-9]{64})(?:\s|$)",
        text,
    )
    return match.group(1) if match else None


def marker_times(text: str, kind: str) -> list[datetime]:
    result: list[datetime] = []
    for line in text.splitlines():
        if f"event={kind} " not in line or "preceding_header_local=" not in line:
            continue
        stamp = field(line, r"preceding_header_local=(\d\d/\d\d/\d\d \d\d:\d\d:\d\d)")
        if not stamp:
            continue
        try:
            result.append(datetime.strptime(stamp, "%m/%d/%y %H:%M:%S"))
        except ValueError:
            continue
    return result


def python_exit_times(text: str) -> list[datetime]:
    times: list[datetime] = []
    for match in re.finditer(
        r"event=dnsbl_python_exit timestamp=(\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(?:\.\d+)?[+-]\d\d:\d\d)",
        text,
    ):
        try:
            times.append(datetime.fromisoformat(match.group(1)))
        except ValueError:
            continue
    return times


def oom_events_after(text: str, baseline: datetime) -> tuple[int, int, str]:
    # Both the console's verbose form and its compact summary may occur;
    # prefer typed events and never count raw private kernel messages.
    events: dict[str, str] = {}
    for match in re.finditer(
        r"Historical kernel OOM victim=(unbound|other) timestamp="
        r"(\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(?:\.\d+)?[+-]\d\d:\d\d)",
        text,
    ):
        try:
            stamp = datetime.fromisoformat(match.group(2))
        except ValueError:
            continue
        if stamp > baseline:
            events[stamp.isoformat()] = match.group(1)
    if not re.search(r"(?m)^log_family=system readable=yes$", text):
        return 0, 0, "UNKNOWN_SYSTEM_LOG_NOT_VERIFIED"
    return len(events), sum(v == "unbound" for v in events.values()), (
        "NEW_KERNEL_OOM_VISIBLE" if events else "NONE_IN_BOUNDED_VISIBLE_LOGS"
    )


def compare(before: str, after: str) -> dict[str, str]:
    a, b = report_time(before), report_time(after)
    if a is None or b is None or b <= a:
        raise ValueError("reports require ordered pfSense_time with UTC offsets")
    old_pid, new_pid = pid(before), pid(after)
    if not old_pid or not new_pid:
        raise ValueError("both reports require a numeric Unbound PID")

    boot = started_local(after)
    if boot is not None:
        # pfSense process start timestamps are local and lack explicit offset.
        boot_in_interval = a.replace(tzinfo=None) <= boot <= b.replace(tzinfo=None)
    else:
        boot_in_interval = False

    def within(start: datetime, end: datetime, values: list[datetime]) -> list[datetime]:
        return [v for v in values if start <= v <= end]

    offsets_match = a.utcoffset() == b.utcoffset()
    begin, finish = a.replace(tzinfo=None), b.replace(tzinfo=None)
    # pfBlockerNG header times have no UTC offset. Refuse correlation
    # across a DST offset change rather than fabricating an ordering.
    stops = within(begin, finish, marker_times(after, "pfblocker_unbound_stop_marker")) if offsets_match else []
    starts = within(begin, finish, marker_times(after, "pfblocker_unbound_start_marker")) if offsets_match else []
    exits = [v for v in python_exit_times(after) if a <= v <= b]
    near_cycle = (
        boot is not None and boot_in_interval
        and any(abs((v - boot).total_seconds()) <= 600 for v in stops)
        and any(abs((v - boot).total_seconds()) <= 600 for v in starts)
        and any(abs((v - boot.replace(tzinfo=b.tzinfo)).total_seconds()) <= 600 for v in exits)
    )
    kills, unbound_kills, oom_state = oom_events_after(after, a)
    changed = old_pid != new_pid
    if changed and near_cycle and kills == 0 and oom_state == "NONE_IN_BOUNDED_VISIBLE_LOGS":
        cause = "PF_BLOCKER_DNSBL_SEQUENCE_CORRELATES_WITH_PID_CHANGE"
    elif changed and near_cycle:
        cause = "RESTART_WITH_MIXED_OR_INCOMPLETE_CAUSE_SIGNALS"
    elif changed:
        cause = "RESTART_CONFIRMED_INITIATOR_NOT_ESTABLISHED"
    else:
        cause = "NO_PID_CHANGE_IN_THIS_INTERVAL"

    out = {
        "baseline_time": a.isoformat(),
        "observation_time": b.isoformat(),
        "unbound_pid_before": old_pid,
        "unbound_pid_after": new_pid,
        "unbound_pid_changed": "yes" if changed else "no",
        "unbound_start_in_window": "yes" if boot_in_interval else "unverified",
        "after_unbound_control": field(after, r"^unbound_control=(\w+)$") or "UNKNOWN",
        "pfblocker_stop_header_in_window": "yes" if stops else "no_or_unverifiable",
        "pfblocker_start_header_in_window": "yes" if starts else "no_or_unverifiable",
        "dnsbl_python_exit_in_window": "yes" if exits else "no_or_unverifiable",
        "kernel_oom_since_baseline": oom_state,
        "kernel_oom_count_visible_since_baseline": str(kills),
        "unbound_oom_count_visible_since_baseline": str(unbound_kills),
        "config_hash_is_not_module_runtime_state": "yes",
        "pfblocker_header_is_not_exact_execution_time": "yes",
        "restart_assessment": cause,
    }
    for name in FINGERPRINTS:
        old_hash, new_hash = fingerprint(before, name), fingerprint(after, name)
        out[f"{name}_hash"] = (
            "MATCH" if old_hash and new_hash and old_hash == new_hash
            else "CHANGED" if old_hash and new_hash
            else "UNKNOWN_MISSING_EVIDENCE"
        )
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--before", required=True, help="sanitized earlier report")
    parser.add_argument("--after", required=True, help="sanitized later report")
    args = parser.parse_args(argv)
    try:
        result = compare(load_report(args.before), load_report(args.after))
    except (ValueError, OSError) as exc:
        print(f"ERROR: unbound_comparison_incomplete: {type(exc).__name__}", file=sys.stderr)
        return 2
    for key, value in result.items():
        print(f"{key}={value}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
